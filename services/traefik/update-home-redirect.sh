#!/bin/sh
# Writes the Traefik rule that sends browsers on the home network to the LAN
# hostname, because the path through Cloudflare is capped by the home uplink.
# Cf-Connecting-Ip equals the public IP of this server only for home clients.
# Sec-Fetch-Dest limits the redirect to page loads: native players, feed clients
# and API calls do not send it, and they may not survive an HTTPS-to-HTTP hop.

set -eu

file=$HOME_REDIRECT_FILE
services=$HOME_REDIRECT_SERVICES
domain_regex=$(printf '%s' "$EXTERNAL_DOMAIN" | sed 's/\./\\./g')

ip=$(wget -qO- --timeout 20 https://www.cloudflare.com/cdn-cgi/trace | sed -n 's/^ip=//p')

# A failed lookup keeps the last rule: a stale IP only means no redirect.
if ! printf '%s\n' "$ip" | grep -Eq '^([0-9]{1,3}\.){3}[0-9]{1,3}$'; then
    printf 'No IPv4 address in the Cloudflare trace response; rule unchanged.\n' >&2
    exit 1
fi

cat >"$file.tmp" <<EOF
# Generated by update-home-redirect.sh. Do not edit.
http:
  routers:
    home-redirect:
      rule: 'HostRegexp(\`^(${services})\.${domain_regex}$\`) && Header(\`Sec-Fetch-Dest\`, \`document\`) && Header(\`Cf-Connecting-Ip\`, \`${ip}\`)'
      priority: 1000
      entryPoints:
        - websecure
      middlewares:
        - home-redirect
      service: noop@internal
      tls:
        certResolver: cloudflare
  middlewares:
    home-redirect:
      redirectRegex:
        regex: '^https?://([^.]+)\.${domain_regex}/(.*)$'
        replacement: 'http://\${1}.${LOCAL_DOMAIN}/\${2}'
EOF

# The rename is atomic, so the Traefik file watcher never reads a partial file.
if cmp -s "$file.tmp" "$file"; then
    rm -f "$file.tmp"
else
    mv "$file.tmp" "$file"
    printf 'Home redirect rule updated.\n'
fi
